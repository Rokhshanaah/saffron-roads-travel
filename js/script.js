const html = document.documentElement;
const header = document.getElementById("site-header");
const hamburger = document.getElementById("hamburger");
const mobileMenu = document.getElementById("mobile-menu");
const themeToggle = document.getElementById("theme-toggle");
const modal = document.getElementById("modal");
const form = document.getElementById("contact-form");
const storyGrid = document.getElementById("story-grid");
const loader = document.getElementById("loader");

let currentLang = "en";
let countersDone = false;

function preferredLang() {
  const saved = localStorage.getItem("saffron-lang");
  if (saved && translations[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("fa")) return "fa";
  if (nav.startsWith("ps")) return "ps";
  return "en";
}

function preferredTheme() {
  const saved = localStorage.getItem("saffron-theme");
  if (saved === "light" || saved === "dark") return saved;
  return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
}

function applyTheme(theme) {
  html.setAttribute("data-theme", theme);
  localStorage.setItem("saffron-theme", theme);
  themeToggle.setAttribute("aria-label", theme === "dark" ? "Switch to light mode" : "Switch to dark mode");
}

function renderStories() {
  const pack = translations[currentLang];
  storyGrid.innerHTML = pack.stories
    .map(
      (item) => `
      <article class="story-card reveal is-inview">
        <p>“${item.quote}”</p>
        <span>${item.name}</span>
      </article>`
    )
    .join("");
}

function applyLang(lang) {
  currentLang = lang;
  const pack = translations[lang];
  html.lang = pack.lang;
  html.dir = pack.dir;
  document.title = pack.title;
  localStorage.setItem("saffron-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (pack[key] !== undefined) {
      if (key === "footer.address") el.innerHTML = pack[key];
      else el.textContent = pack[key];
    }
  });

  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });

  renderStories();
}

function openMenu(open) {
  hamburger.classList.toggle("is-open", open);
  hamburger.setAttribute("aria-expanded", String(open));
  mobileMenu.hidden = !open;
  document.body.classList.toggle("menu-open", open);
}

function openModal(placeKey) {
  const place = translations[currentLang].places[placeKey];
  if (!place) return;
  document.getElementById("modal-image").src = place.image;
  document.getElementById("modal-image").alt = place.title;
  document.getElementById("modal-meta").textContent = place.meta;
  document.getElementById("modal-title").textContent = place.title;
  document.getElementById("modal-text").textContent = place.text;
  modal.hidden = false;
  document.body.classList.add("menu-open");
}

function closeModal() {
  modal.hidden = true;
  if (mobileMenu.hidden) document.body.classList.remove("menu-open");
}

function validateForm() {
  const pack = translations[currentLang];
  const name = form.name.value.trim();
  const email = form.email.value.trim();
  const destination = form.destination.value;
  const message = form.message.value.trim();
  const emailOk = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
  const errors = {
    name: name.length < 2 ? pack["err.name"] : "",
    email: emailOk ? "" : pack["err.email"],
    destination: destination ? "" : pack["err.destination"],
    message: message.length < 10 ? pack["err.message"] : "",
  };

  Object.entries(errors).forEach(([field, messageText]) => {
    const input = form.elements[field];
    const wrap = input.closest(".field");
    wrap.classList.toggle("has-error", Boolean(messageText));
    wrap.querySelector(".error").textContent = messageText;
  });

  return !Object.values(errors).some(Boolean);
}

function animateCounters() {
  if (countersDone) return;
  countersDone = true;
  document.querySelectorAll("[data-count]").forEach((el) => {
    const target = Number(el.dataset.count);
    const start = performance.now();
    const tick = (now) => {
      const progress = Math.min((now - start) / 1100, 1);
      el.textContent = String(Math.round(target * (1 - Math.pow(1 - progress, 3))));
      if (progress < 1) requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  });
}

function revealIfVisible(el) {
  const rect = el.getBoundingClientRect();
  if (rect.top < window.innerHeight - 40 && rect.bottom > 80) {
    el.classList.add("is-inview");
  }
}

function observeReveals() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-inview");
          if (entry.target.classList.contains("hero-stats") || entry.target.closest(".hero-stats")) {
            animateCounters();
          }
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.05, rootMargin: "80px 0px -20px 0px" }
  );

  document.querySelectorAll(".reveal, .hero-stats").forEach((el) => {
    revealIfVisible(el);
    observer.observe(el);
  });
}

function spyNav() {
  const links = [...document.querySelectorAll(".nav-links a")];
  const sections = links
    .map((link) => document.querySelector(link.getAttribute("href")))
    .filter(Boolean);

  const onScroll = () => {
    header.classList.toggle("is-scrolled", window.scrollY > 12);
    const y = window.scrollY + 120;
    let current = sections[0];
    sections.forEach((section) => {
      if (section.offsetTop <= y) current = section;
    });
    links.forEach((link) => {
      link.classList.toggle("is-active", link.getAttribute("href") === `#${current.id}`);
    });
  };

  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
}

